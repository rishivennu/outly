let bits: Uint8Array | null = null;
function mask() {
  if (bits) return bits;
  const bin = atob(LAND_B64);
  bits = new Uint8Array(LAND_W * LAND_H);
  for (let i = 0; i < bin.length; i++) {
    const v = bin.charCodeAt(i);
    for (let j = 0; j < 8; j++) bits[i * 8 + j] = (v >> (7 - j)) & 1;
  }
  return bits;
}

/** True when (lat, lng) in degrees is on land. */
export function isLand(lat: number, lng: number) {
  const x = Math.min(LAND_W - 1, Math.max(0, Math.floor(((lng + 180) / 360) * LAND_W)));
  const y = Math.min(LAND_H - 1, Math.max(0, Math.floor(((90 - lat) / 180) * LAND_H)));
  return mask()[y * LAND_W + x] === 1;
}

