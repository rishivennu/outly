/** Any text: upper-cased, characters without a glyph are dropped (so they never leave a gap). */
export function DotText({ text: raw, className = "h-9" }: { text: string; className?: string }) {
  const text = [...raw.toUpperCase()].filter((c) => GLYPH[c]).join("");
  const dots = useMemo(() => {
    const out: { x: number; y: number }[] = [];
    [...text].forEach((ch, ci) => {
      const g = GLYPH[ch];
      if (!g) return;
      g.forEach((row, ry) =>
        [...row].forEach((on, rx) => {
          if (on !== "1") return;
          for (let dy = 0; dy < 2; dy++) for (let dx = 0; dx < 2; dx++) out.push({ x: ci * 12 + rx * 2 + dx, y: ry * 2 + dy });
        }),
      );
    });
    return out;
  }, [text]);
  const cols = Math.max(1, text.length * 12 - 2);
  return (
    <svg aria-hidden="true" className={`la-dots shrink-0 ${className}`} viewBox={`0 0 ${cols} 14`} style={{ aspectRatio: `${cols} / 14` }}>
      {dots.map((d, k) => (
        <circle key={k} cx={d.x + 0.5} cy={d.y + 0.5} r={0.46} fill="currentColor" />
      ))}
    </svg>
  );
}
